"""LLM clients behind one small interface.

Three implementations:

* :class:`GroqClient` -- a real HTTP client, reads ``GROQ_API_KEY`` from the environment.
* :class:`ReplayClient` -- reads recorded responses from disk. No network, no key.
* :class:`RecordingClient` -- wraps a real client and writes fixtures as it goes.

The replay client is not a convenience. **The entire test suite and the whole evaluation
run with no API key at all**, which is what makes the numbers in the README reproducible
by anyone who clones the repository. A project whose headline metric can only be
regenerated by the author with their own credentials has not really reported a metric.

The key never appears in a log line, an error message or a repr. It is read from the
environment at call time and passed straight to the request.
"""

from __future__ import annotations

import json
import os
import time
from dataclasses import dataclass
from pathlib import Path
from typing import Callable, Protocol, runtime_checkable

from ..errors import SQLEngineError

# Verified available on 2026-09-09 by listing /openai/v1/models with a real key.
# NOTE: the widely-documented "llama-3.3-70b-versatile" is NOT served to every
# account -- it 404s on keys that do not have it, which reads like a broken
# client rather than a model-access problem. Prefer a model confirmed by the
# listing endpoint over one confirmed by a blog post.
DEFAULT_GROQ_MODEL = "openai/gpt-oss-120b"
GROQ_ENDPOINT = "https://api.groq.com/openai/v1/chat/completions"

# Groq sits behind Cloudflare, which rejects requests carrying the default
# python-requests/urllib User-Agent with "HTTP 403 -- error code: 1010".
# That is a *browser signature* block, not an authentication failure, so the
# error is deeply misleading: a perfectly valid key looks revoked. Sending an
# ordinary browser UA is what makes the same key return 200.
_BROWSER_UA = (
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 "
    "(KHTML, like Gecko) Chrome/126.0 Safari/537.36"
)


class LLMError(SQLEngineError):
    """Raised when a completion cannot be obtained."""


class FixtureMissingError(LLMError):
    """Raised when the replay client has no recording for a prompt key.

    Loud on purpose. A replay client that quietly returned an empty string would turn
    "the fixture set is incomplete" into "the model got this one wrong", which would
    corrupt the evaluation numbers in the flattering direction.
    """


@dataclass(frozen=True, slots=True)
class Prompt:
    """One request to a model.

    ``key`` is what makes replay possible: a stable identifier for this turn
    (``"golden-017/attempt-1"``). The real client ignores it entirely. Deriving the key
    from a hash of the prompt text instead would invalidate every fixture the moment a
    word of the system prompt changed.
    """

    system: str
    user: str
    key: str


@runtime_checkable
class LLMClient(Protocol):
    """Anything that can turn a :class:`Prompt` into text."""

    name: str

    def complete(self, prompt: Prompt) -> str:
        """Return the model's raw response text."""
        ...


class GroqClient:
    """Calls Groq's OpenAI-compatible chat completions endpoint."""

    def __init__(
        self,
        model: str = DEFAULT_GROQ_MODEL,
        *,
        temperature: float = 0.0,
        timeout: float = 60.0,
        api_key: str | None = None,
        max_attempts: int = 5,
        sleep: Callable[[float], None] = time.sleep,
    ) -> None:
        self.name = f"groq:{model}"
        self.model = model
        # Temperature 0 is not about quality, it is about reproducibility: a recorded
        # fixture is only meaningful if re-recording it would give roughly the same
        # thing.
        self.temperature = temperature
        self.timeout = timeout
        self._api_key = api_key or os.environ.get("GROQ_API_KEY")
        self._max_attempts = max_attempts
        self._sleep = sleep  # injected so tests never actually wait

    @property
    def available(self) -> bool:
        return bool(self._api_key)

    def _retry_delay(self, response: "requests.Response", attempt: int) -> float:
        """Seconds to wait before retrying.

        Prefer the server's own ``Retry-After`` -- it knows when the window resets and
        we do not. Groq also sends ``x-ratelimit-reset-tokens`` (e.g. ``"3.615s"``),
        which is the useful one here because the token budget is what actually runs
        out. Only if neither is present do we guess with exponential backoff.
        """
        header = response.headers.get("retry-after") or response.headers.get(
            "x-ratelimit-reset-tokens", ""
        )
        if header:
            try:
                return min(60.0, float(str(header).rstrip("s")) + 0.5)
            except ValueError:
                pass
        return min(60.0, 2.0 * (2 ** (attempt - 1)))

    def complete(self, prompt: Prompt) -> str:
        if not self._api_key:
            raise LLMError(
                "GROQ_API_KEY is not set. Set it, or use ReplayClient with the "
                "committed fixtures (which need no key)."
            )
        import requests  # imported lazily so the package works with no network stack

        headers = {
            "Authorization": f"Bearer {self._api_key}",
            "Content-Type": "application/json",
            # Required. Without it Cloudflare returns 403/1010 -- see _BROWSER_UA.
            "User-Agent": _BROWSER_UA,
        }
        body = {
            "model": self.model,
            "temperature": self.temperature,
            "messages": [
                {"role": "system", "content": prompt.system},
                {"role": "user", "content": prompt.user},
            ],
        }

        # Groq's free tier limits TOKENS per window, not just requests. A batch of
        # schema-carrying prompts exhausts the token budget long before the request
        # budget: measured 8,000 tokens/window against 1,000 requests/day, so a 45
        # question evaluation 429s from roughly question 19 onward while the request
        # counter still reads 970-odd remaining. Without this retry the failures look
        # like model failures -- the recorder marked them "unrecovered" -- which would
        # have quietly understated the model and produced a fabricated accuracy number.
        # Honour Retry-After when the server sends it; fall back to exponential backoff.
        last_error = ""
        for attempt in range(1, self._max_attempts + 1):
            response = requests.post(
                GROQ_ENDPOINT, headers=headers, json=body, timeout=self.timeout
            )
            if response.status_code == 200:
                break
            last_error = (
                f"HTTP {response.status_code}: {_safe_error_text(response.text)}"
            )
            retryable = response.status_code == 429 or response.status_code >= 500
            if not retryable or attempt == self._max_attempts:
                # The body can echo request headers on some errors, so only the status
                # and the provider's own message are surfaced -- never what we sent.
                raise LLMError(f"Groq returned {last_error}")
            self._sleep(self._retry_delay(response, attempt))
        else:  # pragma: no cover - loop always breaks or raises
            raise LLMError(f"Groq returned {last_error}")

        payload = response.json()
        try:
            return payload["choices"][0]["message"]["content"]
        except (KeyError, IndexError, TypeError) as error:
            raise LLMError(f"unexpected Groq response shape: {error}") from None

    def __repr__(self) -> str:
        return f"GroqClient(model={self.model!r}, key_present={self.available})"


def _safe_error_text(text: str, limit: int = 300) -> str:
    try:
        parsed = json.loads(text)
        message = parsed.get("error", {}).get("message")
        if isinstance(message, str):
            return message[:limit]
    except (json.JSONDecodeError, AttributeError):
        pass
    return text[:limit]


class ReplayClient:
    """Serves recorded responses from a JSON file keyed by :attr:`Prompt.key`."""

    def __init__(self, fixtures: dict[str, str], name: str = "replay") -> None:
        self.name = name
        self._fixtures = fixtures
        #: Keys actually requested during this run, so a test can assert the repair
        #: loop made the number of calls it claims to have made.
        self.calls: list[str] = []

    @classmethod
    def from_file(cls, path: str | Path) -> ReplayClient:
        path = Path(path)
        if not path.exists():
            raise FixtureMissingError(f"fixture file {path} does not exist")
        payload = json.loads(path.read_text(encoding="utf-8"))
        return cls(payload["responses"], name=payload.get("recorded_from", "replay"))

    def complete(self, prompt: Prompt) -> str:
        self.calls.append(prompt.key)
        try:
            return self._fixtures[prompt.key]
        except KeyError:
            raise FixtureMissingError(
                f"no recorded response for prompt key {prompt.key!r}. "
                "Re-record with evaluation/record_fixtures.py, or check the key."
            ) from None

    def __contains__(self, key: object) -> bool:
        return key in self._fixtures

    def __repr__(self) -> str:
        return f"ReplayClient(name={self.name!r}, responses={len(self._fixtures)})"


class RecordingClient:
    """Wraps a real client and appends every response to a fixture file.

    Writes after *every* call rather than at the end, so a run that dies halfway leaves
    a usable partial fixture set instead of nothing.
    """

    def __init__(self, inner: LLMClient, path: str | Path) -> None:
        self.name = f"recording[{inner.name}]"
        self._inner = inner
        self._path = Path(path)
        self._responses: dict[str, str] = {}
        if self._path.exists():
            existing = json.loads(self._path.read_text(encoding="utf-8"))
            self._responses = existing.get("responses", {})

    def complete(self, prompt: Prompt) -> str:
        if prompt.key in self._responses:
            return self._responses[prompt.key]  # resumable: never re-pay for a call
        response = self._inner.complete(prompt)
        self._responses[prompt.key] = response
        self._flush()
        return response

    def _flush(self) -> None:
        self._path.parent.mkdir(parents=True, exist_ok=True)
        self._path.write_text(
            json.dumps(
                {"recorded_from": self._inner.name, "responses": self._responses},
                indent=2,
                sort_keys=True,
            ),
            encoding="utf-8",
        )


class StaticClient:
    """Returns the same response every time. For unit tests of the repair loop."""

    def __init__(self, responses: list[str], name: str = "static") -> None:
        self.name = name
        self._responses = list(responses)
        self.calls: list[str] = []

    def complete(self, prompt: Prompt) -> str:
        self.calls.append(prompt.key)
        index = min(len(self.calls) - 1, len(self._responses) - 1)
        return self._responses[index]


